def _config_cell(run_id: str, token: str, api_base: str, dataset_filename: str, extra: dict) -> dict:
    lines = [
        "# ⚙️ Configuration (generated by the app — no need to edit)",
        f"API_BASE = {api_base.rstrip('/')!r}",
        f"RUN_ID = {run_id!r}",
        f"RUN_TOKEN = {token!r}  # lets this notebook read the dataset and report results for this run only",
        f"DATASET_FILENAME = {dataset_filename!r}",
    ] + [f"{k} = {json.dumps(v) if isinstance(v, (list, dict)) else repr(v)}" for k, v in extra.items()]
    return _code("\n".join(lines))


def _shared_cell() -> dict:
    src = inspect.getsource(shared_data)
    return _code("# Same dataset discovery and train/test split as the app's CPU training\n" + src)


def _intro(title: str, what: str) -> dict:
    return _md(f"""
    # {title}

    {what}

    **Steps**
    1. `Runtime → Change runtime type → T4 GPU` (free).
    2. `Runtime → Run all`.
    3. Watch the results appear in the app. If the app is not reachable from Colab, the notebook switches to
       manual mode: upload your dataset when asked, then upload the downloaded `results.json` into the app.

    Free Colab sessions can disconnect after a few hours; finished models are already reported, so you can
    re-run the notebook to continue.
    """)


def image_classification_notebook(run_id: str, token: str, api_base: str, dataset_filename: str,
                                  model_keys: list[str], custom: list[str], epochs: int, time_limit_min: int) -> dict:
    models = [[k, get_model(k).name, get_model(k).params["timm_model"]] for k in model_keys]
    models += [[f"image_classification/colab/{c}", c, c] for c in custom]
    cfg = {"MODELS": models, "EPOCHS": epochs, "TIME_LIMIT_MIN": time_limit_min, "BATCH": 32, "LR": 3e-4,
           "PATIENCE": 4, "SEED": 42}
    train = '''
    import numpy as np, torch, torch.nn as nn, timm
    from PIL import Image
    from torch.utils.data import Dataset, DataLoader
    from sklearn.metrics import (accuracy_score, balanced_accuracy_score, f1_score, precision_score,
                                 recall_score, confusion_matrix)

    torch.manual_seed(SEED)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    if device == "cpu":
        print("⚠️ No GPU! Use Runtime → Change runtime type → T4 GPU, then run again.")

    root, items, notes = prepare_image_items(DATA_PATH)
    for n in notes: print("note:", n)
    classes = sorted({it["label"] for it in items}); cidx = {c: i for i, c in enumerate(classes)}
    train_idx, test_idx = make_image_split(items)
    tr_pos, va_pos = make_row_split([items[i]["label"] for i in train_idx], test_size=0.1, seed=SEED)
    tr_idx, va_idx = [train_idx[i] for i in tr_pos], [train_idx[i] for i in va_pos]
    print(f"{len(classes)} classes | train {len(tr_idx)} | val {len(va_idx)} | test {len(test_idx)}")

    class DS(Dataset):
        def __init__(self, idx, tf): self.idx, self.tf = idx, tf
        def __len__(self): return len(self.idx)
        def __getitem__(self, k):
            it = items[self.idx[k]]
            return self.tf(Image.open(os.path.join(root, it["path"])).convert("RGB")), cidx[it["label"]]

    @torch.no_grad()
    def predict(model, dl):
        model.eval(); P, Y = [], []
        for x, y in dl:
            with torch.autocast(device_type=device, enabled=device == "cuda"):
                P.append(model(x.to(device, non_blocking=True)).argmax(1).cpu()); Y.append(y)
        return torch.cat(Y).numpy(), torch.cat(P).numpy()

    os.makedirs("/content/models", exist_ok=True)
    for mi, (key, name, timm_name) in enumerate(MODELS):
        report_status("running", f"Fine-tuning {name} ({mi + 1}/{len(MODELS)})", mi, len(MODELS))
        t0 = time.time(); model = None
        try:
            model = timm.create_model(timm_name, pretrained=True, num_classes=len(classes)).to(device)
            cfg = timm.data.resolve_data_config({}, model=model)
            train_tf = timm.data.create_transform(**cfg, is_training=True, auto_augment="rand-m9-mstd0.5")
            eval_tf = timm.data.create_transform(**cfg)
            dl_tr = DataLoader(DS(tr_idx, train_tf), batch_size=BATCH, shuffle=True, num_workers=2,
                               pin_memory=True, drop_last=len(tr_idx) > BATCH)
            dl_va = DataLoader(DS(va_idx, eval_tf), batch_size=BATCH * 2, num_workers=2)
            dl_te = DataLoader(DS(test_idx, eval_tf), batch_size=BATCH * 2, num_workers=2)
            opt = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=0.05)
            sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=LR, total_steps=EPOCHS * len(dl_tr), pct_start=0.1)
            scaler = torch.amp.GradScaler(enabled=device == "cuda")
            loss_fn = nn.CrossEntropyLoss(label_smoothing=0.1)
            best_va, best_state, bad, epochs_run = -1.0, None, 0, 0
            for ep in range(EPOCHS):
                model.train()
                for x, y in dl_tr:
                    x, y = x.to(device, non_blocking=True), y.to(device, non_blocking=True)
                    opt.zero_grad(set_to_none=True)
                    with torch.autocast(device_type=device, enabled=device == "cuda"):
                        loss = loss_fn(model(x), y)
                    scaler.scale(loss).backward(); scaler.step(opt); scaler.update(); sched.step()
                yv, pv = predict(model, dl_va)
                va_acc = float(accuracy_score(yv, pv)); epochs_run = ep + 1
                print(f"  {name} epoch {ep + 1}/{EPOCHS} val_acc={va_acc:.4f}")
                if va_acc > best_va:
                    best_va, bad = va_acc, 0
                    best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
                else:
                    bad += 1
                if bad >= PATIENCE or time.time() - t0 > TIME_LIMIT_MIN * 60:
                    break
            model.load_state_dict(best_state)
            yt, pt = predict(model, dl_te)
            metrics = {
                "accuracy": accuracy_score(yt, pt), "balanced_accuracy": balanced_accuracy_score(yt, pt),
                "f1_macro": f1_score(yt, pt, average="macro", zero_division=0),
                "precision_macro": precision_score(yt, pt, average="macro", zero_division=0),
                "recall_macro": recall_score(yt, pt, average="macro", zero_division=0),
            }
            torch.save({"state_dict": best_state, "timm_model": timm_name, "classes": classes},
                       f"/content/models/{timm_name.replace('/', '_')}.pt")
            details = {"epochs_run": epochs_run, "best_val_accuracy": best_va, "classes": classes}
            if len(classes) <= 30:
                details["confusion_matrix"] = confusion_matrix(yt, pt, labels=list(range(len(classes)))).tolist()
            report_result({"model_key": key, "name": name, "status": "completed",
                           "metrics": {k: float(v) for k, v in metrics.items()},
                           "train_seconds": time.time() - t0, "params": {"timm_model": timm_name, "epochs": EPOCHS,
                           "lr": LR, "batch_size": BATCH, "img_size": cfg["input_size"][-1]}, "details": details})
        except Exception as e:
            report_result({"model_key": key, "name": name, "status": "failed", "error": repr(e)[:2000],
                           "train_seconds": time.time() - t0})
        finally:
            del model
            if device == "cuda": torch.cuda.empty_cache()
    '''
    return _notebook([
        _intro("Image classification: GPU fine-tuning", "Fine-tunes every selected pretrained network end to end and compares them on the same test images as the app."),
        _config_cell(run_id, token, api_base, dataset_filename, cfg),
        _code("!pip -q install timm"),
        _code(_COMMON_HELPERS),
        _code(_GET_DATA),
        _shared_cell(),
        _code(train),
        _code(_FINISH),
    ])


def text_classification_notebook(run_id: str, token: str, api_base: str, dataset_filename: str,
                                 model_keys: list[str], custom: list[str], epochs: int, time_limit_min: int,
                                 text_column: str, target: str) -> dict:
    models = [[k, get_model(k).name, get_model(k).params["hf_model"]] for k in model_keys]
    models += [[f"text_classification/colab/{c}", c, c] for c in custom]
    cfg = {"MODELS": models, "EPOCHS": epochs, "TIME_LIMIT_MIN": time_limit_min, "TEXT_COLUMN": text_column,
           "TARGET": target, "BATCH": 16, "LR": 2e-5, "MAX_LEN": 256, "SEED": 42}
    train = '''
    import numpy as np, torch
    from torch.utils.data import DataLoader
    from transformers import AutoTokenizer, AutoModelForSequenceClassification, get_linear_schedule_with_warmup
    from sklearn.metrics import (accuracy_score, balanced_accuracy_score, f1_score, precision_score,
                                 recall_score, confusion_matrix)

    torch.manual_seed(SEED)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    if device == "cpu":
        print("⚠️ No GPU! Use Runtime → Change runtime type → T4 GPU, then run again.")

    df = load_table(DATA_PATH)
    df = df[df[TARGET].notna()]
    labels = df[TARGET].astype(str)
    counts = labels.value_counts()
    keep = ~labels.isin(counts[counts < 3].index)
    df, labels = df[keep], labels[keep]
    texts = df[TEXT_COLUMN].fillna("").astype(str).tolist()
    classes = sorted(labels.unique()); cidx = {c: i for i, c in enumerate(classes)}
    y = np.array([cidx[l] for l in labels])
    train_idx, test_idx = make_row_split(labels.to_numpy())
    tr_pos, va_pos = make_row_split(labels.to_numpy()[train_idx], test_size=0.1, seed=SEED)
    tr_idx, va_idx = [train_idx[i] for i in tr_pos], [train_idx[i] for i in va_pos]
    print(f"{len(classes)} classes | train {len(tr_idx)} | val {len(va_idx)} | test {len(test_idx)}")

    def batches(tok, idx, shuffle):
        def collate(b):
            enc = tok([texts[i] for i in b], truncation=True, max_length=MAX_LEN, padding=True, return_tensors="pt")
            enc["labels"] = torch.tensor(y[b]); return enc
        return DataLoader(idx, batch_size=BATCH if shuffle else BATCH * 4, shuffle=shuffle, collate_fn=collate)

    @torch.no_grad()
    def predict(model, dl):
        model.eval(); P, Y = [], []
        for b in dl:
            Y.append(b.pop("labels"))
            with torch.autocast(device_type=device, enabled=device == "cuda"):
                P.append(model(**{k: v.to(device) for k, v in b.items()}).logits.argmax(-1).cpu())
        return torch.cat(Y).numpy(), torch.cat(P).numpy()

    for mi, (key, name, hf) in enumerate(MODELS):
        report_status("running", f"Fine-tuning {name} ({mi + 1}/{len(MODELS)})", mi, len(MODELS))
        t0 = time.time(); model = None
        try:
            tok = AutoTokenizer.from_pretrained(hf)
            model = AutoModelForSequenceClassification.from_pretrained(hf, num_labels=len(classes)).to(device)
            dl_tr, dl_va, dl_te = batches(tok, tr_idx, True), batches(tok, va_idx, False), batches(tok, test_idx, False)
            opt = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=0.01)
            sched = get_linear_schedule_with_warmup(opt, int(0.06 * EPOCHS * len(dl_tr)), EPOCHS * len(dl_tr))
            scaler = torch.amp.GradScaler(enabled=device == "cuda")
            best_va, best_state, epochs_run = -1.0, None, 0
            for ep in range(EPOCHS):
                model.train()
                for b in dl_tr:
                    b = {k: v.to(device) for k, v in b.items()}
                    opt.zero_grad(set_to_none=True)
                    with torch.autocast(device_type=device, enabled=device == "cuda"):
                        loss = model(**b).loss
                    scaler.scale(loss).backward(); scaler.unscale_(opt)
                    torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                    scaler.step(opt); scaler.update(); sched.step()
                yv, pv = predict(model, dl_va)
                va = float(f1_score(yv, pv, average="macro")); epochs_run = ep + 1
                print(f"  {name} epoch {ep + 1}/{EPOCHS} val_f1={va:.4f}")
                if va > best_va:
                    best_va = va
                    best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
                if time.time() - t0 > TIME_LIMIT_MIN * 60:
                    break
            model.load_state_dict(best_state)
            yt, pt = predict(model, dl_te)
            metrics = {
                "accuracy": accuracy_score(yt, pt), "balanced_accuracy": balanced_accuracy_score(yt, pt),
                "f1_macro": f1_score(yt, pt, average="macro", zero_division=0),
                "precision_macro": precision_score(yt, pt, average="macro", zero_division=0),
                "recall_macro": recall_score(yt, pt, average="macro", zero_division=0),
            }
            details = {"epochs_run": epochs_run, "best_val_f1": best_va}
            if len(classes) <= 30:
                details["confusion_matrix"] = confusion_matrix(yt, pt, labels=list(range(len(classes)))).tolist()
            report_result({"model_key": key, "name": name, "status": "completed",
                           "metrics": {k: float(v) for k, v in metrics.items()}, "train_seconds": time.time() - t0,
                           "params": {"hf_model": hf, "epochs": EPOCHS, "lr": LR, "max_len": MAX_LEN}, "details": details})
        except Exception as e:
            report_result({"model_key": key, "name": name, "status": "failed", "error": repr(e)[:2000],
                           "train_seconds": time.time() - t0})
        finally:
            del model
            if device == "cuda": torch.cuda.empty_cache()
    '''
    return _notebook([
        _intro("Text classification: GPU fine-tuning", "Fine-tunes every selected transformer end to end and compares them on the same test rows as the app."),
        _config_cell(run_id, token, api_base, dataset_filename, cfg),
        _code("!pip -q install transformers sentencepiece openpyxl"),
        _code(_COMMON_HELPERS),
        _code(_GET_DATA),
        _shared_cell(),
        _code(train),
        _code(_FINISH),
    ])


def object_detection_notebook(run_id: str, token: str, api_base: str, dataset_filename: str,
                              model_keys: list[str], epochs: int, time_limit_min: int) -> dict:
    models = [[k, get_model(k).name, get_model(k).params["weights"]] for k in model_keys]
    cfg = {"MODELS": models, "EPOCHS": epochs, "TIME_LIMIT_MIN": time_limit_min, "IMG_SIZE": 640, "SEED": 42}
    train = '''
    import glob, yaml, torch
    from ultralytics import YOLO

    root = unwrap_root(DATA_PATH)
    yaml_path = sorted(glob.glob(f"{root}/**/*.y*ml", recursive=True))[0]
    cfg = yaml.safe_load(open(yaml_path)) or {}
    cfg["path"] = os.path.dirname(yaml_path)
    if "val" not in cfg:
        cfg["val"] = cfg["train"]
        print("note: no validation split given; validating on train (scores will be optimistic)")
    fixed_yaml = "/content/data_fixed.yaml"
    yaml.safe_dump(cfg, open(fixed_yaml, "w"))
    print("classes:", cfg.get("names"))

    for mi, (key, name, weights) in enumerate(MODELS):
        report_status("running", f"Training {name} ({mi + 1}/{len(MODELS)})", mi, len(MODELS))
        t0 = time.time()
        try:
            model = YOLO(weights)
            model.train(data=fixed_yaml, epochs=EPOCHS, imgsz=IMG_SIZE, seed=SEED, time=TIME_LIMIT_MIN / 60,
                        project="/content/runs", name=key.replace("/", "_"), exist_ok=True, verbose=False)
            m = model.val(data=fixed_yaml, imgsz=IMG_SIZE, verbose=False).box
            metrics = {"map50_95": float(m.map), "map50": float(m.map50), "precision": float(m.mp), "recall": float(m.mr)}
            report_result({"model_key": key, "name": name, "status": "completed", "metrics": metrics,
                           "train_seconds": time.time() - t0,
                           "params": {"weights": weights, "epochs": EPOCHS, "imgsz": IMG_SIZE}, "details": {}})
        except Exception as e:
            report_result({"model_key": key, "name": name, "status": "failed", "error": repr(e)[:2000],
                           "train_seconds": time.time() - t0})
        finally:
            if torch.cuda.is_available(): torch.cuda.empty_cache()
    '''
    return _notebook([
        _intro("Object detection: GPU training", "Trains every selected YOLO / RT-DETR detector on your labelled images and compares them."),
        _config_cell(run_id, token, api_base, dataset_filename, cfg),
        _code("!pip -q install ultralytics"),
        _code(_COMMON_HELPERS),
        _code(_GET_DATA),
        _shared_cell(),
        _code(train),
        _code(_FINISH),
    ])
